/**
 * Extract the marked regions of the example pages into `src/generated/snippets.gen.ts`.
 *
 * The alternative — writing the shown code out by hand next to each demo — drifts. It drifts
 * quietly, too: the page keeps rendering, the snippet keeps looking plausible, and the first person
 * to copy it finds out. Generating from the files that actually run means the code on screen cannot
 * disagree with the demo above it.
 *
 * Regions are marked in the sources themselves:
 *
 *   <!-- #region basic -->  …markup…  <!-- #endregion -->      in a .html
 *   // #region basic        …setup…   // #endregion            in a .ts
 *
 * A region id may appear once per language per page. The `.html` half becomes `template`, the `.ts`
 * half becomes `setup`, and either may be absent.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const examples = fileURLToPath(new URL('..', import.meta.url));
const pagesDir = join(examples, 'src/pages');
const outFile = join(examples, 'src/generated/snippets.gen.ts');

const HTML_REGION = /<!--\s*#region\s+([\w-]+)\s*-->([\s\S]*?)<!--\s*#endregion\s*-->/g;
const TS_REGION = /\/\/\s*#region\s+([\w-]+)\s*\n([\s\S]*?)\/\/\s*#endregion/g;

/**
 * Strip the indentation the region carried from its surroundings, without touching the relative
 * indentation inside it. Measured over non-blank lines only — a blank line has no indentation to
 * measure and would otherwise force the common prefix to zero.
 */
function dedent(text) {
  // Normalise line endings first. Git checks these files out with CRLF on Windows, and a stray \r
  // survives into the rendered `<pre>`, defeats the leading-blank-line trim, and lands in whatever
  // the reader copies out.
  const lines = text.replace(/\r\n/g, '\n').replace(/^\n+/, '').replace(/\s+$/, '').split('\n');
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^[ \t]*/)[0].length);
  const common = indents.length ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(common)).join('\n');
}

function collect(file, pattern, key, out) {
  const source = readFileSync(file, 'utf8');
  const page = basename(file, extname(file));
  pattern.lastIndex = 0;
  let match;
  let found = 0;
  while ((match = pattern.exec(source)) !== null) {
    const [, id, body] = match;
    const slot = (out[id] ??= { page });
    if (slot[key] !== undefined) {
      throw new Error(`gen-snippets: region "${id}" appears twice as ${key} (${file})`);
    }
    slot[key] = dedent(body);
    found++;
  }
  return found;
}

const snippets = {};
let regions = 0;

if (existsSync(pagesDir)) {
  for (const entry of readdirSync(pagesDir).sort()) {
    const file = join(pagesDir, entry);
    if (entry.endsWith('.html')) regions += collect(file, HTML_REGION, 'template', snippets);
    else if (entry.endsWith('.ts')) regions += collect(file, TS_REGION, 'setup', snippets);
  }
}

const body = Object.entries(snippets)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, snippet]) => `  ${JSON.stringify(id)}: ${JSON.stringify(snippet, null, 2).replace(/\n/g, '\n  ')},`)
  .join('\n');

const file = `// Generated by examples/tools/gen-snippets.mjs — do not edit.
//
// Each entry is a region marked in the page that renders the demo, so what is shown is what runs.

export interface Snippet {
  /** The page the region was taken from. */
  page: string;
  /** Markup half of the region, if the page's .html marked one. */
  template?: string;
  /** Script half of the region, if the page's .ts marked one. */
  setup?: string;
}

export const SNIPPETS: Record<string, Snippet> = {
${body}
};
`;

mkdirSync(join(examples, 'src/generated'), { recursive: true });
writeFileSync(outFile, file);

process.stdout.write(`ok  gen-snippets: ${regions} region(s) -> ${Object.keys(snippets).length} snippet(s)\n`);
