/**
 * Guard: this repository must not describe who or what authored it.
 *
 * Named for what it checks, not for the words it forbids — a name containing one of its own patterns
 * would make the gate flag its own wiring, and a gate whose first act is a false positive on itself does
 * not earn trust.
 *
 * Runs in CI over tracked file CONTENT and over commit messages not yet on the remote, so the rule
 * travels with the repository rather than living in one machine's `.git/hooks` (which git neither
 * versions nor clones). If it fires, the fix is to DELETE the sentence — not to spell the word
 * differently. Routing around a gate that is telling you something true defeats the point of having it.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

/**
 * Wordings that claim authorship, not the bare word "AI".
 *
 * Weave has real AI-facing surfaces — an MCP server, editor integrations, the skills — and prose about
 * those is product documentation, not a trace of how the code was written. A gate that flags legitimate
 * subject matter gets switched off, which is worse than having no gate at all.
 */
const PATTERNS = [
  /\bAI[-\s]?(assisted|generated|authored|written)\b/i,
  /\bAI[-\s]traces?\b/i,
  /\b(written|authored|generated|produced)\s+(by|with)\s+(an?\s+)?(AI|assistant|model|agent)\b/i,
  /\bco-?authored-by:\s*(?!.*@users\.noreply\.github\.com)/i,
];

/**
 * Specific vendor names are NOT listed here, deliberately: a public file enumerating the names a project
 * refuses to mention is itself the disclosure it is trying to prevent — it tells a reader exactly what is
 * being kept out. This file catches authorship CLAIMS; a bare vendor name in a tracked file is a known
 * hole rather than an oversight, and closing it would require publishing the list.
 */

/** Files where these words are legitimate subject matter. */
const ALLOW = [/^tools\/verify-authorship\.mjs$/];

/** Not text — reading these yields mojibake that trips any pattern by chance. */
const BINARY = /\.(vsix|zip|png|jpg|jpeg|gif|ico|woff2?|ttf|eot|pdf|jar|gz|tgz|webp|avif|mp4|wasm)$/i;

const sh = (args) => {
  const r = spawnSync('git', args, { encoding: 'utf8' });
  if (r.status !== 0) {
    console.error('x git failed:', r.stderr);
    process.exit(1);
  }
  return r.stdout;
};

const scan = (label, text) => {
  let hits = 0;
  text.split(/\r?\n/).forEach((line, i) => {
    for (const re of PATTERNS) {
      if (re.test(line)) {
        console.error(`  ${label}:${i + 1}  ${line.trim().slice(0, 110)}`);
        hits++;
        break;
      }
    }
  });
  return hits;
};

console.log('\ntools/verify-authorship.mjs');

// SELF-CHECK. A gate that cannot fail is not a gate — prove the patterns bite before trusting a clean
// result. (An earlier copy of this file in the main repository shipped with its escapes mangled, so every
// pattern was unmatchable and it passed on a repository that plainly failed it.)
const CANARY = 'this line was AI-generated by an assistant';
if (!PATTERNS.some((re) => re.test(CANARY))) {
  console.error('x the patterns do not match their own canary — this gate is not functioning');
  process.exit(1);
}

let failures = 0;

const tracked = sh(['ls-files'])
  .split('\n')
  .map((l) => l.trim())
  .filter(Boolean);
for (const file of tracked) {
  if (BINARY.test(file) || ALLOW.some((re) => re.test(file))) continue;
  let text;
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  failures += scan(file, text);
}

// Commit messages not yet on the remote — still rewritable, and the last chance to catch one.
const range = spawnSync('git', ['rev-list', 'origin/main..HEAD'], { encoding: 'utf8' });
if (range.status === 0) {
  for (const sha of range.stdout
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)) {
    failures += scan(`commit ${sha.slice(0, 8)}`, sh(['log', '-1', '--format=%B', sha]));
  }
}

if (failures) {
  console.error(
    `\nx ${failures} line(s) describe how this repository is authored.\n` +
      '  Delete the sentence. Do not respell the word to satisfy the pattern — the gate is right.\n'
  );
  process.exit(1);
}
console.log(`ok  no authorship claims in ${tracked.length} tracked files or the unpushed commit messages\n`);
